export function Icon({ name, size = 16, weight = 2, className, style }: { name: string; size?: number; weight?: number; className?: string; style?: React.CSSProperties }) {
  const Component = map[name] ?? Circle;
  const filled = name.endsWith(".fill") && ["stop", "play", "pause", "mic", "pin", "person"].some((p) => name.startsWith(p));
  return <Component size={size} strokeWidth={weight} className={className} style={style} fill={filled ? "currentColor" : "none"} aria-hidden />;
}
